// Writes packages/mail/src/brand-mark-png.ts from the one master mark, site/public/brand-mark.svg:
// the mark rendered by Chrome to an 84 px PNG (28 px in the email header at 3x), as base64, with the
// master's SHA-256 so a test fails if the master changes and this file is not regenerated.
// The PDF draws the same mark from vector paths in packages/mail/src/brand.ts.
// Usage: npm run brand:mail
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { chromium } from "playwright";

const SIZE = 84;
const root = new URL("../", import.meta.url);
const master = await readFile(new URL("site/public/brand-mark.svg", root), "utf8");

const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage({ viewport: { width: SIZE, height: SIZE } });
await page.setContent(`<html><body style="margin:0;background:transparent"><img src="data:image/svg+xml;base64,${Buffer.from(master).toString("base64")}" width="${SIZE}" height="${SIZE}"></body></html>`);
const png = await page.screenshot({ omitBackground: true });
await browser.close();

const sha256 = createHash("sha256").update(master).digest("hex");
await writeFile(
  new URL("packages/mail/src/brand-mark-png.ts", root),
  `// Generated by scripts/brand-mail.ts from site/public/brand-mark.svg. Do not edit.
export const BRAND_MARK_MASTER_SHA256 = "${sha256}";
export const BRAND_MARK_PNG_SIZE = ${SIZE};
export const BRAND_MARK_PNG_BASE64 =
  "${png.toString("base64")}";
`,
);
console.log(`brand mark PNG written: ${SIZE}x${SIZE}, ${png.length} bytes`);
